//Types of variables//

/* In C, there are several types of variables, we'll cover a 2 principals types::
   - int: for integer values
   - float: for floating-point values

/**int and float **/

#include <stdio.h>

int main() {
    int integer = 5; // 5 is a integer value, like in math with Z set of numbers.
    float floating = 5.5; // 5.5 is a floating-point value, like in math with Q set of numbers.

    printf("Integer value: %d\n", integer); // %d is a format specifier for integer values.
    printf("Floating-point value: %.2f\n", floating); // %.2f is a format specifier for floating-point values, it indicates that we want to print the value with
}